const char *tdx_professional_kind_name(tdx_professional_kind kind) {
    if (kind < TDX_PROFESSIONAL_STOCK || kind > TDX_PROFESSIONAL_BOARD)
        return "unknown";
    return tables[kind].name;
}

int tdx_professional_kind_parse(const char *text, size_t length, tdx_professional_kind *out) {
    size_t index;
    if (!text || !out)
        return 0;
    for (index = 0; index < sizeof(tables) / sizeof(tables[0]); ++index) {
        size_t name_length = strlen(tables[index].name);
        if (name_length == length && memcmp(text, tables[index].name, length) == 0) {
            *out = (tdx_professional_kind)index;
            return 1;
        }
    }
    return 0;
}

const char *tdx_professional_field_name(tdx_professional_kind kind, unsigned id) {
    size_t index;
    if (kind < TDX_PROFESSIONAL_STOCK || kind > TDX_PROFESSIONAL_BOARD)
        return NULL;
    for (index = 0; index < tables[kind].count; ++index)
        if (tables[kind].entries[index].id == id)
            return tables[kind].entries[index].name;
    /* Not listed.  An id the table does not publish names nothing, and saying so is the
     * only honest answer - the samples do carry such ids. */
    return NULL;
}

size_t tdx_professional_field_count(tdx_professional_kind kind) {
    if (kind < TDX_PROFESSIONAL_STOCK || kind > TDX_PROFESSIONAL_BOARD)
        return 0;
    return tables[kind].count;
}

/* A date is either absent (zero) or a real calendar date.  The day range is checked
 * against the month rather than against 31 in general, so 20260231 is refused. */
static int date_is_sane(uint32_t date) {
    unsigned year;
    unsigned month;
    unsigned day;
    static const unsigned lengths[13] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};

    if (date == 0)
        return 1;
    year = date / 10000;
    month = date / 100 % 100;
    day = date % 100;
    if (year < 1900 || year > 2200 || month < 1 || month > 12 || day < 1)
        return 0;
    if (day > lengths[month]) {
        /* February gains a day in a leap year, which the reference's 1..31 check does not
         * model; refusing a real 29 February would be worse than allowing an impossible
         * 31 February, so the calendar is checked properly here. */
        int leap = (year % 4 == 0 && year % 100 != 0) || year % 400 == 0;
        if (!(month == 2 && leap && day == 29))
            return 0;
    }
    return 1;
}

static uint32_t read_u32(const uint8_t *data) {
    return (uint32_t)data[0] | ((uint32_t)data[1] << 8) | ((uint32_t)data[2] << 16) |
           ((uint32_t)data[3] << 24);
}

static float read_f32(const uint8_t *data) {
    float value;
    uint32_t bits = read_u32(data);
    memcpy(&value, &bits, sizeof(value));
    return value;
}

int tdx_professional_parse_trading(const uint8_t *data, size_t size,
                                   tdx_professional_record *out, size_t capacity,
                                   size_t *out_count, tdx_error *err) {
    size_t records;
    size_t index;

    if (out_count)
        *out_count = 0;
    if (!data || !out) {
        tdx_error_set(err, "parsing a professional-data file needs bytes and an output");
        return TDX_ERR;
    }
    if (size % TDX_PROFESSIONAL_TRADING_RECORD_SIZE != 0) {
        /* The record size is settled by every sample dividing by it exactly, so a
         * remainder means this is not that format - not that there is a partial trailing
         * record to ignore. */
        tdx_error_set(err, "professional trading file of %zu bytes is not a multiple of %d",
                      size, TDX_PROFESSIONAL_TRADING_RECORD_SIZE);
        return TDX_ERR;
    }
    records = size / TDX_PROFESSIONAL_TRADING_RECORD_SIZE;
    if (records > capacity) {
        tdx_error_set(err, "professional trading file holds %zu records, more than %zu",
                      records, capacity);
        return TDX_ERR;
    }
    for (index = 0; index < records; ++index) {
        const uint8_t *record = data + index * TDX_PROFESSIONAL_TRADING_RECORD_SIZE;
        uint32_t date = read_u32(record + 1);
        if (!date_is_sane(date)) {
            tdx_error_set(err, "professional trading record %zu has date %u", index, date);
            return TDX_ERR;
        }
        out[index].id = record[0];
        out[index].date = date;
        out[index].first = read_f32(record + 5);
        out[index].second = read_f32(record + 9);
    }
    if (out_count)
        *out_count = records;
    return TDX_OK;
}

int tdx_professional_summarize(const tdx_professional_record *records, size_t count,
                               tdx_professional_kind kind, tdx_professional_id_summary *out,
                               size_t capacity, size_t *out_count, tdx_error *err) {
    size_t written = 0;
    size_t index;

    if (out_count)
        *out_count = 0;
    if (!records || !out) {
        tdx_error_set(err, "summarizing professional data needs records and an output");
        return TDX_ERR;
    }
    for (index = 0; index < count; ++index) {
        size_t scan;
        tdx_professional_id_summary *slot = NULL;
        for (scan = 0; scan < written; ++scan)
            if (out[scan].id == records[index].id) {
                slot = &out[scan];
                break;
            }
        if (!slot) {
            if (written >= capacity) {
                tdx_error_set(err, "professional data holds more than %zu distinct fields",
                              capacity);
                return TDX_ERR;
            }
            slot = &out[written];
            memset(slot, 0, sizeof(*slot));
            slot->id = records[index].id;
            slot->name = tdx_professional_field_name(kind, records[index].id);
            slot->has_values = 1;
            slot->first_min = records[index].first;
            slot->first_max = records[index].first;
            written++;
        }
        slot->count++;
        if (records[index].date != 0) {
            if (slot->first_date == 0 || records[index].date < slot->first_date)
                slot->first_date = records[index].date;
            if (records[index].date > slot->last_date)
                slot->last_date = records[index].date;
        }
        if (isfinite(records[index].first)) {
            if (records[index].first < slot->first_min)
                slot->first_min = records[index].first;
            if (records[index].first > slot->first_max)
                slot->first_max = records[index].first;
        }
    }
    /* Ascending by id, so the summary reads the same way whatever order the file used. */
    for (index = 1; index < written; ++index) {
        tdx_professional_id_summary key = out[index];
        size_t position = index;
        while (position > 0 && out[position - 1].id > key.id) {
            out[position] = out[position - 1];
            position--;
        }
        out[position] = key;
    }
    if (out_count)
        *out_count = written;
    return TDX_OK;
}

int tdx_professional_select(const tdx_professional_record *records, size_t count,
                            const tdx_professional_selection *selection, size_t *indices,
                            size_t capacity, size_t *out_count, tdx_error *err) {
    size_t written = 0;
    size_t index;
    int ranged;

    if (out_count)
        *out_count = 0;
    if (!records || !indices || !selection) {
        tdx_error_set(err, "selecting professional data needs records, a selection and room");
        return TDX_ERR;
    }
    ranged = selection->from != 0 || selection->to != 0;
    for (index = 0; index < count; ++index) {
        if (selection->id != 0 && records[index].id != selection->id)
            continue;
        if (ranged) {
            /* A record with no date cannot be said to fall inside a range, so it is left
             * out rather than guessed at. */
            if (records[index].date == 0)
                continue;
            if (selection->from != 0 && records[index].date < selection->from)
                continue;
            if (selection->to != 0 && records[index].date > selection->to)
                continue;
        }
        if (written >= capacity) {
            tdx_error_set(err, "the selection matched more than %zu records", capacity);
            return TDX_ERR;
        }
        indices[written++] = index;
    }
    if (out_count)
        *out_count = written;
    return TDX_OK;
}
