static void test_parse_daily(void) {
    tdx_kline_page page;
    tdx_error error;
    error.message[0] = '\0';
    tdx_kline_page_init(&page);

    CHECK(tdx_kline_parse(daily_reply, sizeof(daily_reply), 4, 0, &page, &error) == TDX_OK,
          "daily parse: %s", error.message);
    CHECK(page.count == 6, "six bars, got %zu", page.count);
    if (page.count == 6) {
        const tdx_kline_bar *first = &page.bars[0];
        const tdx_kline_bar *last = &page.bars[5];
        CHECK(first->date == 20260914, "the first date %d", first->date);
        CHECK(first->hour == 15 && first->minute == 0, "a daily bar is stamped 15:00, got %02d:%02d",
              first->hour, first->minute);
        CHECK(first->open == 17.56, "open %.3f", first->open);
        CHECK(first->high == 17.68, "high %.3f", first->high);
        CHECK(first->low == 17.48, "low %.3f", first->low);
        CHECK(first->close == 17.58, "close %.3f", first->close);
        CHECK(first->volume == 6421189, "volume %lld", (long long)first->volume);
        CHECK(first->amount > 112760727.0 && first->amount < 112760729.0, "amount %.2f",
              first->amount);
        CHECK(!first->has_extras, "a stock bar carries no breadth fields");
        CHECK(last->date == 20260921, "the last date %d", last->date);
        CHECK(last->close == 17.75, "the last close %.3f", last->close);
        CHECK(last->volume == 8738903, "the last volume %lld", (long long)last->volume);
        /* Every bar must satisfy its own envelope. */
        {
            size_t index;
            for (index = 0; index < page.count; ++index) {
                const tdx_kline_bar *bar = &page.bars[index];
                CHECK(bar->high >= bar->low, "bar %zu high %.3f below low %.3f", index,
                      bar->high, bar->low);
                CHECK(bar->open <= bar->high && bar->open >= bar->low,
                      "bar %zu open %.3f outside [%.3f, %.3f]", index, bar->open, bar->low,
                      bar->high);
                CHECK(bar->close <= bar->high && bar->close >= bar->low,
                      "bar %zu close %.3f outside [%.3f, %.3f]", index, bar->close, bar->low,
                      bar->high);
            }
        }
    }
    tdx_kline_page_free(&page);
}

static void test_parse_minute(void) {
    tdx_kline_page page;
    tdx_error error;
    error.message[0] = '\0';
    tdx_kline_page_init(&page);

    CHECK(tdx_kline_parse(minute_reply, sizeof(minute_reply), 7, 0, &page, &error) == TDX_OK,
          "minute parse: %s", error.message);
    CHECK(page.count == 6, "six bars, got %zu", page.count);
    if (page.count == 6) {
        const tdx_kline_bar *first = &page.bars[0];
        CHECK(first->date == 20260921, "the intraday date comes from an LC1 word: %d",
              first->date);
        CHECK(first->hour == 14 && first->minute == 55, "the first bar is 14:55, got %02d:%02d",
              first->hour, first->minute);
        CHECK(first->open == 17.76 && first->close == 17.76, "open %.3f close %.3f",
              first->open, first->close);
        CHECK(first->high == 17.77 && first->low == 17.75, "high %.3f low %.3f", first->high,
              first->low);
        CHECK(first->volume == 47500, "volume %lld", (long long)first->volume);
        /* The fixture runs 14:55..15:00, so the last bar is the close. */
        CHECK(page.bars[5].hour == 15 && page.bars[5].minute == 0,
              "the last bar is 15:00, got %02d:%02d", page.bars[5].hour, page.bars[5].minute);
    }
    tdx_kline_page_free(&page);
}

static void test_parse_index(void) {
    tdx_kline_page page;
    tdx_error error;
    error.message[0] = '\0';
    tdx_kline_page_init(&page);

    CHECK(tdx_kline_parse(index_reply, sizeof(index_reply), 4, 1, &page, &error) == TDX_OK,
          "index parse: %s", error.message);
    CHECK(page.count == 4, "four bars, got %zu", page.count);
    if (page.count == 4) {
        CHECK(page.bars[0].date == 20260916, "the first date %d", page.bars[0].date);
        CHECK(page.bars[0].has_extras == 1, "index mode must read the breadth fields");
        CHECK(page.bars[0].extra_1 == 1650 && page.bars[0].extra_2 == 608,
              "breadth %u/%u", (unsigned)page.bars[0].extra_1,
              (unsigned)page.bars[0].extra_2);
        CHECK(page.bars[0].close > 3800.0 && page.bars[0].close < 4000.0,
              "an index close is a different scale, got %.2f", page.bars[0].close);
        CHECK(page.bars[2].extra_1 == 1756 && page.bars[2].extra_2 == 519, "breadth %u/%u",
              (unsigned)page.bars[2].extra_1, (unsigned)page.bars[2].extra_2);
    }
    tdx_kline_page_free(&page);

    /* The same index bytes without index mode must be rejected: the four breadth
     * bytes are then read as the next record's date, which is not a date.  That
     * is the check that keeps the two record shapes from being conflated. */
    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(index_reply, sizeof(index_reply), 4, 0, &page, &error) == TDX_ERR,
          "index bytes parsed as a stock series must be rejected");
    CHECK(strstr(error.message, "invalid daily") != NULL,
          "the mismatch surfaces as a bad date, got: %s", error.message);
    tdx_kline_page_free(&page);
}

static void test_parse_rejects(void) {
    tdx_kline_page page;
    tdx_error error;
    uint8_t body[64];
    error.message[0] = '\0';

    tdx_kline_page_init(&page);
    {
        static const uint8_t empty_page[2] = {0x00, 0x00};
        CHECK(tdx_kline_parse(empty_page, sizeof(empty_page), 4, 0, &page, &error) == TDX_OK,
              "a page with no bars is legal; the walk just stops");
    }
    tdx_kline_page_free(&page);

    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(daily_reply, 1, 4, 0, &page, &error) == TDX_ERR,
          "a one-byte body must be rejected");
    tdx_kline_page_free(&page);

    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(daily_reply, sizeof(daily_reply) - 3, 4, 0, &page, &error) == TDX_ERR,
          "a truncated final record must be rejected");
    tdx_kline_page_free(&page);

    /* A count that exceeds the 800 cap. */
    memset(body, 0, sizeof(body));
    body[0] = 0x21;
    body[1] = 0x03; /* 801 */
    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(body, sizeof(body), 4, 0, &page, &error) == TDX_ERR,
          "a count above 800 must be rejected");
    CHECK(strstr(error.message, "above the") != NULL, "the error must say why: %s",
          error.message);
    tdx_kline_page_free(&page);

    /* A count with no records behind it. */
    memset(body, 0, sizeof(body));
    body[0] = 0x02;
    body[1] = 0x00;
    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(body, 2, 4, 0, &page, &error) == TDX_ERR,
          "a count with no records must be rejected");
    tdx_kline_page_free(&page);

    /* An impossible daily date. */
    memset(body, 0, sizeof(body));
    body[0] = 0x01;
    body[1] = 0x00;
    body[2] = 0x00;
    body[3] = 0x00;
    body[4] = 0x00;
    body[5] = 0x00; /* date 0 */
    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(body, sizeof(body), 4, 0, &page, &error) == TDX_ERR,
          "date 0 must be rejected");
    CHECK(strstr(error.message, "invalid daily") != NULL, "the error must name the field: %s",
          error.message);
    tdx_kline_page_free(&page);

    /* A record that claims more bytes than the body holds. */
    tdx_kline_page_init(&page);
    CHECK(tdx_kline_parse(daily_reply, 8, 4, 0, &page, &error) == TDX_ERR,
          "a record with no price fields must be rejected");
    tdx_kline_page_free(&page);
}

/* --- sorting and rendering -------------------------------------------- */

static void test_sort(void) {
    tdx_kline_bar bars[4];
    memset(bars, 0, sizeof(bars));
    bars[0].date = 20260102;
    bars[0].hour = 15;
    bars[1].date = 20260101;
    bars[1].hour = 15;
    bars[2].date = 20260102;
    bars[2].hour = 9;
    bars[2].minute = 30;
    bars[3].date = 20260101;
    bars[3].hour = 9;
    bars[3].minute = 31;
    tdx_kline_sort(bars, 4);
    CHECK(bars[0].date == 20260101 && bars[0].hour == 9 && bars[0].minute == 31,
          "the earliest bar first, got %d %02d:%02d", bars[0].date, bars[0].hour,
          bars[0].minute);
    CHECK(bars[1].date == 20260101 && bars[1].hour == 15, "then the same day's close");
    CHECK(bars[2].date == 20260102 && bars[2].hour == 9, "then the next day's open");
    CHECK(bars[3].date == 20260102 && bars[3].hour == 15, "then the last bar");
}

/* Counts structural braces outside string literals. */
static int braces_balanced(const char *text) {
    int depth = 0;
    int in_string = 0;
    int escaped = 0;
    const char *cursor;
    for (cursor = text; *cursor; ++cursor) {
        if (in_string) {
            if (escaped)
                escaped = 0;
            else if (*cursor == '\\')
                escaped = 1;
            else if (*cursor == '"')
                in_string = 0;
            continue;
        }
        if (*cursor == '"')
            in_string = 1;
        else if (*cursor == '{')
            depth++;
        else if (*cursor == '}') {
            depth--;
            if (depth < 0)
                return 0;
        }
    }
    return !in_string && depth == 0;
}

static void test_json_rendering(void) {
    tdx_kline_series series;
    tdx_kline_page page;
    tdx_buf line;
    tdx_error error;
    char text[4096];
    size_t copy;

    error.message[0] = '\0';
    tdx_kline_series_init(&series);
    tdx_kline_page_init(&page);
    tdx_buf_init(&line);
    CHECK(tdx_kline_parse(daily_reply, sizeof(daily_reply), 4, 0, &page, &error) == TDX_OK,
          "parse: %s", error.message);
    series.bars = page.bars;
    series.count = page.count;
    series.capacity = page.capacity;
    series.pages = 1;
    series.page_size = 6;
    series.period_id = 4;
    series.index_mode = 0;
    series.reached_end = 1;

    CHECK(tdx_kline_format_bar(&line, &series.bars[0], 0, "000623", "day", &error) == TDX_OK,
          "bar render: %s", error.message);
    copy = line.len < sizeof(text) - 1 ? line.len : sizeof(text) - 1;
    memcpy(text, line.data, copy);
    text[copy] = '\0';
    CHECK(braces_balanced(text), "the bar object must be balanced: %s", text);
    CHECK(strstr(text, "\"type\":\"kline\"") != NULL, "the bar type");
    CHECK(strstr(text, "\"security_id\":\"SZ000623\"") != NULL, "the identity");
    CHECK(strstr(text, "\"period\":\"day\"") != NULL, "the period");
    CHECK(strstr(text, "\"date\":20260914") != NULL, "the date");
    CHECK(strstr(text, "\"time\":\"15:00\"") != NULL, "the time");
    CHECK(strstr(text, "\"open\":17.560") != NULL, "open");
    CHECK(strstr(text, "\"volume\":6421189") != NULL, "volume");
    CHECK(strstr(text, "\"extra_1\":null") != NULL, "a stock bar has null breadth");

    tdx_buf_clear(&line);
    CHECK(tdx_kline_format_summary(&line, &series, 0, "000623", "day", 0, "1.2.3.4:7709",
                                   &error) == TDX_OK,
          "summary render: %s", error.message);
    copy = line.len < sizeof(text) - 1 ? line.len : sizeof(text) - 1;
    memcpy(text, line.data, copy);
    text[copy] = '\0';
    CHECK(braces_balanced(text), "the summary must be balanced: %s", text);
    CHECK(text[line.len - 1] == '}', "the summary must end with '}'");
    CHECK(strstr(text, "\"type\":\"kline_summary\"") != NULL, "the summary type");
    CHECK(strstr(text, "\"bar_count\":6") != NULL, "the bar count");
    CHECK(strstr(text, "\"first_date\":20260914") != NULL, "the first date");
    CHECK(strstr(text, "\"last_date\":20260921") != NULL, "the last date");
    CHECK(strstr(text, "\"index_mode\":false") != NULL, "the index flag");
    CHECK(strstr(text, "\"high\":") != NULL && strstr(text, "\"low\":") != NULL,
          "a populated series reports its envelope: %s", text);

    /* An empty series must render nulls rather than invented zeros. */
    memset(&series, 0, sizeof(series));
    tdx_buf_clear(&line);
    CHECK(tdx_kline_format_summary(&line, &series, 0, "000623", "day", 0, NULL, &error) == TDX_OK,
          "empty summary render: %s", error.message);
    copy = line.len < sizeof(text) - 1 ? line.len : sizeof(text) - 1;
    memcpy(text, line.data, copy);
    text[copy] = '\0';
    CHECK(braces_balanced(text), "an empty summary must be balanced: %s", text);
    CHECK(strstr(text, "\"first_date\":null") != NULL, "missing dates render null");
    CHECK(strstr(text, "\"high\":null") != NULL, "an empty envelope renders null");
    CHECK(strstr(text, "\"endpoint\":null") != NULL, "a missing endpoint renders null");

    tdx_buf_free(&line);
    tdx_kline_page_free(&page);
}

int main(void) {
    test_periods();
    test_lc1_date();
    test_block_index_code();
    test_request();
    test_parse_daily();
    test_parse_minute();
    test_parse_index();
    test_parse_rejects();
    test_sort();
    test_json_rendering();

    if (failures) {
        printf("%d kline check(s) failed\n", failures);
        return 1;
    }
    printf("kline checks passed\n");
    return 0;
}
