/* test_kline.c - 0x052D multi-period K-lines.
 *
 * The three reply fixtures are the bytes a live public node returned; they cover
 * a daily series, an intraday series and an index series, which between them
 * exercise both date encodings and the optional breadth fields.  See
 * output/kline_probe_evidence.txt.
 *
 * The daily fixture is also the point where four independent sources agree:
 * the 20260612 bar decoded here reads open 16.79 / high 17.49 / low 16.73 /
 * close 17.39 / volume 16826060, and the same day's zst_cache image reports
 * 05=16.790000 06=17.490000 07=16.730000 08=17.390000 10=16826061. */
#include <stdio.h>
#include <string.h>

#include "tdx_kline.h"
#include "tdx_kline_json.h"

/* The three reply fixtures are the bytes a live public node returned.  They are
 * generated by output/make_kline_fixtures.py from output/kline_probe_evidence.txt
 * rather than pasted in by hand, so the test reads the server's actual stream.
 *
 * Between them they cover a daily series, an intraday series and an index series,
 * which exercises both date encodings and the optional breadth fields.
 *
 * The daily series is also where four independent sources agree: the 20260612 bar
 * reads open 16.79 / high 17.49 / low 16.73 / close 17.39 / volume 16826060, and
 * the same day's zst_cache image reports 05=16.790000 06=17.490000 07=16.730000
 * 08=17.390000 10=16826061. */
#include "kline_fixtures.h"

static int failures = 0;

#define CHECK(condition, ...)                                                        \
    do {                                                                             \
        if (!(condition)) {                                                          \
            printf("FAIL %s:%d: ", __FILE__, __LINE__);                              \
            printf(__VA_ARGS__);                                                     \
            printf("\n");                                                            \
            failures++;                                                              \
        }                                                                            \
    } while (0)

/* --- periods ---------------------------------------------------------- */

static void test_periods(void) {
    tdx_kline_period period;
    tdx_error error;
    error.message[0] = '\0';

    CHECK(tdx_kline_period_parse("day", &period, &error) == TDX_OK &&
              period.id == 4 && period.intraday == 0 && strcmp(period.name, "day") == 0,
          "day: %s", error.message);
    CHECK(tdx_kline_period_parse("week", &period, &error) == TDX_OK && period.id == 5 &&
              period.intraday == 0,
          "week");
    CHECK(tdx_kline_period_parse("month", &period, &error) == TDX_OK && period.id == 6 &&
              period.intraday == 0,
          "month");
    CHECK(tdx_kline_period_parse("5m", &period, &error) == TDX_OK && period.id == 0 &&
              period.intraday == 1,
          "5m");
    CHECK(tdx_kline_period_parse("15m", &period, &error) == TDX_OK && period.id == 1, "15m");
    CHECK(tdx_kline_period_parse("30m", &period, &error) == TDX_OK && period.id == 2, "30m");
    CHECK(tdx_kline_period_parse("60m", &period, &error) == TDX_OK && period.id == 3, "60m");
    CHECK(tdx_kline_period_parse("1h", &period, &error) == TDX_OK && period.id == 3 &&
              strcmp(period.name, "60m") == 0,
          "1h is an alias of 60m");
    /* time and 1m share period 7; the canonical name distinguishes them. */
    CHECK(tdx_kline_period_parse("time", &period, &error) == TDX_OK && period.id == 7 &&
              strcmp(period.name, "time") == 0,
          "time");
    CHECK(tdx_kline_period_parse("1m", &period, &error) == TDX_OK && period.id == 7 &&
              strcmp(period.name, "1m") == 0,
          "1m maps to the same id but keeps its own name");
    CHECK(tdx_kline_period_parse("DAILY", &period, &error) == TDX_OK && period.id == 4,
          "the name is case folded");
    CHECK(tdx_kline_period_parse(" day ", &period, &error) == TDX_OK && period.id == 4,
          "the name is trimmed");
    CHECK(tdx_kline_period_parse("tick", &period, &error) == TDX_ERR, "an unknown period fails");
    CHECK(tdx_kline_period_parse("", &period, &error) == TDX_ERR, "an empty period fails");
}

static void test_lc1_date(void) {
    tdx_error error;
    int date = 0;
    error.message[0] = '\0';
    /* year = word / 2048 + 2004, remainder = month * 100 + day.  So the word is
     * not a day count: 101 is 1 January and 309 is 9 March of the base year. */
    CHECK(tdx_kline_lc1_date(101, &date, &error) == TDX_OK && date == 20040101,
          "word 101 is 20040101, got %d (%s)", date, error.message);
    CHECK(tdx_kline_lc1_date(0x0135, &date, &error) == TDX_OK && date == 20040309,
          "word 0x0135 is 9 March of the base year, got %d", date);
    CHECK(tdx_kline_lc1_date(4096 + 101, &date, &error) == TDX_OK && date == 20060101,
          "two years later, got %d", date);
    /* 20260612 -> (2026-2004)*2048 + 612 = 45668. */
    CHECK(tdx_kline_lc1_date(45668, &date, &error) == TDX_OK && date == 20260612,
          "20260612, got %d (%s)", date, error.message);
    CHECK(tdx_kline_lc1_date(0xFFFF, &date, &error) == TDX_ERR,
          "0xFFFF decodes to month 1023 and must be refused");
}

static void test_block_index_code(void) {
    CHECK(tdx_kline_is_block_index_code("880301"), "880xxx is a block index");
    CHECK(tdx_kline_is_block_index_code("881001"), "881xxx is a block index");
    CHECK(!tdx_kline_is_block_index_code("000623"), "an ordinary code is not");
    CHECK(!tdx_kline_is_block_index_code("88030"), "five digits is not");
    CHECK(!tdx_kline_is_block_index_code("88030a"), "a non-digit is not");
    CHECK(!tdx_kline_is_block_index_code(NULL), "null is not");
}

/* --- requests --------------------------------------------------------- */

static void test_request(void) {
    tdx_buf request;
    tdx_error error;
    size_t index;
    int all_zero_tail = 1;
    error.message[0] = '\0';
    tdx_buf_init(&request);

    CHECK(tdx_kline_build_request(0, "000623", 4, 0, 6, &request, &error) == TDX_OK, "build: %s",
          error.message);
    CHECK(request.len == TDX_KLINE_REQUEST_SIZE, "the body is %zu bytes, expected %u",
          request.len, (unsigned)TDX_KLINE_REQUEST_SIZE);
    if (request.len == TDX_KLINE_REQUEST_SIZE) {
        CHECK(tdx_u16le(request.data) == 0, "market at +0");
        CHECK(memcmp(request.data + 2, "000623", 6) == 0, "the code sits at +2");
        CHECK(tdx_u16le(request.data + 8) == 4, "period id at +8");
        CHECK(tdx_u16le(request.data + 10) == TDX_KLINE_PERIOD_PARAMETER,
              "the period parameter at +10 is always 1");
        CHECK(tdx_u16le(request.data + 12) == 0, "start at +12");
        CHECK(tdx_u16le(request.data + 14) == 6, "count at +14");
        for (index = 16; index < request.len; ++index)
            if (request.data[index] != 0)
                all_zero_tail = 0;
        CHECK(all_zero_tail, "the 26 bytes after the count must be zero");
    }

    CHECK(tdx_kline_build_request(1, "000001", 7, 100, 800, &request, &error) == TDX_OK,
          "id 7 with a full page: %s", error.message);
    if (request.len == TDX_KLINE_REQUEST_SIZE) {
        CHECK(tdx_u16le(request.data) == 1, "market 1");
        CHECK(tdx_u16le(request.data + 8) == 7, "period 7");
        CHECK(tdx_u16le(request.data + 12) == 100, "start 100");
        CHECK(tdx_u16le(request.data + 14) == 800, "count 800");
    }

    /* A short code leaves the gap zero padded rather than shifting the fields. */
    CHECK(tdx_kline_build_request(0, "1A", 4, 0, 1, &request, &error) == TDX_OK,
          "a short code: %s", error.message);
    if (request.len == TDX_KLINE_REQUEST_SIZE) {
        CHECK(request.data[2] == '1' && request.data[3] == 'A' && request.data[4] == 0,
              "the code must be left aligned and zero padded");
        CHECK(tdx_u16le(request.data + 8) == 4, "the period field must not shift");
    }

    CHECK(tdx_kline_build_request(0, "000623", 4, 0, 0, &request, &error) == TDX_ERR,
          "a zero count must be refused");
    CHECK(tdx_kline_build_request(0, "000623", 4, 0, 801, &request, &error) == TDX_ERR,
          "a count above 800 must be refused");
    CHECK(tdx_kline_build_request(3, "000623", 4, 0, 6, &request, &error) == TDX_ERR,
          "market 3 must be refused");
    CHECK(tdx_kline_build_request(0, "0006237", 4, 0, 6, &request, &error) == TDX_ERR,
          "a seven-character code must be refused");
    CHECK(tdx_kline_build_request(0, "00062-", 4, 0, 6, &request, &error) == TDX_ERR,
          "a punctuation character must be refused");
    CHECK(tdx_kline_build_request(0, "000623", 12, 0, 6, &request, &error) == TDX_ERR,
          "period 12 is outside the known range");
    tdx_buf_free(&request);
}

